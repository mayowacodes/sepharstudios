/** VTT parser: extracts cue timestamps + text. Tolerant of WEBVTT header,
*  blank-line separators, and `NOTE`/`STYLE` blocks (which we skip). */
function parseVtt(vtt) {
	const cues = [];
	const blocks = vtt.replace(/\r\n/g, "\n").split(/\n\n+/);
	for (const block of blocks) {
		const lines = block.split("\n").filter(Boolean);
		if (lines.length === 0) continue;
		if (lines[0] === "WEBVTT" || lines[0].startsWith("NOTE") || lines[0].startsWith("STYLE")) continue;
		const tsLine = lines.find((l) => l.includes("-->"));
		if (!tsLine) continue;
		const [startRaw] = tsLine.split("-->");
		const startSec = vttTimeToSeconds(startRaw.trim());
		if (Number.isNaN(startSec)) continue;
		const text = lines.slice(lines.indexOf(tsLine) + 1).join(" ").replace(/<[^>]+>/g, "").trim();
		if (!text) continue;
		cues.push({
			startSec,
			text
		});
	}
	return cues;
}
function vttTimeToSeconds(ts) {
	const parts = ts.split(":");
	const sec = parseFloat(parts.pop() ?? "0");
	const min = parseInt(parts.pop() ?? "0", 10);
	return parseInt(parts.pop() ?? "0", 10) * 3600 + min * 60 + sec;
}
/** Sample cues to a manageable digest size. Take every Nth cue so we
*  cover the full timeline rather than just the first few minutes. */
function digest(cues, maxChars) {
	if (cues.length === 0) return "";
	let stride = 1;
	while (cues.slice(0, 9999).filter((_, i) => i % stride === 0).reduce((acc, c) => acc + c.text.length + 12, 0) > maxChars) {
		stride += 1;
		if (stride > 50) break;
	}
	return cues.filter((_, i) => i % stride === 0).map((c) => `[${Math.round(c.startSec)}s] ${c.text}`).join("\n");
}
